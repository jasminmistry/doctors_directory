function normalizeSlug(value: string | null | undefined): string {
  return (value ?? "").trim().toLowerCase()
}

export function isRemovedProductSlug(slug: string | null | undefined): boolean {
  const value = normalizeSlug(slug)
  return value.length > 0 && REMOVED_PRODUCT_SLUGS.has(value)
}

export function isRemovedBrandHub(brand: string | null | undefined): boolean {
  const value = normalizeSlug(brand)
  if (value.length === 0) return false
  return REMOVED_BRAND_HUBS.has(value) || REMOVED_BRAND_HUBS.has(toUrlSlug(value))
}

export function isRedirectedCategorySlug(slug: string | null | undefined): boolean {
  const value = normalizeSlug(slug)
  return value.length > 0 && REDIRECT_CATEGORY_SLUGS.has(value)
}

export function filterRemovedProducts<T extends { slug?: string | null }>(
  items: readonly T[]
): T[] {
  return items.filter((item) => !isRemovedProductSlug(item.slug))
}

export function filterRemovedBrands(brands: readonly string[]): string[] {
  return brands.filter((brand) => !isRemovedBrandHub(brand))
}
